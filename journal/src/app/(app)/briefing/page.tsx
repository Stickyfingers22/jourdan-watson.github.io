import Link from "next/link";
import { requireUser } from "@/lib/supabase/server";
import { briefingMarkdown, gatherSnapshot } from "@/lib/insights";
import { saveBriefing } from "@/lib/briefing-actions";
import { isUuid } from "@/lib/records";
import { shortDate } from "@/lib/format";
import { Markdown } from "@/components/Markdown";
import { CopyButton } from "@/components/CopyButton";

export default async function Briefing({ searchParams }: { searchParams: Promise<{ report?: string }> }) {
  const { report } = await searchParams;
  const { supabase } = await requireUser();
  const { data: past } = await supabase
    .from("reports")
    .select("id,title,created_at")
    .eq("kind", "weekly_briefing")
    .order("created_at", { ascending: false })
    .limit(20);

  let body: string;
  let heading = "Live briefing";
  if (report && isUuid(report)) {
    const { data } = await supabase.from("reports").select("title,body").eq("id", report).maybeSingle();
    body = data?.body ?? "Report not found.";
    heading = data?.title ?? "Saved briefing";
  } else {
    body = briefingMarkdown(await gatherSnapshot(supabase), true);
  }

  return (
    <div className="mx-auto grid max-w-6xl gap-6 lg:grid-cols-[1fr_16rem]">
      <div className="space-y-4">
        <header className="flex flex-wrap items-end justify-between gap-3">
          <div>
            <p className="h2">Workflow A · Executive Intelligence</p>
            <h1 className="h1">{heading}</h1>
          </div>
          <div className="flex gap-2">
            <CopyButton text={body} label="Copy markdown" />
            {!report && (
              <form action={saveBriefing}><button className="btn">Save to archive</button></form>
            )}
          </div>
        </header>
        <article className="card"><Markdown source={body} /></article>
        <p className="text-xs text-muted">
          Generated by rules on your own data — no AI API, no cost. For deeper analysis, use the{" "}
          <Link href="/assistant" className="underline">AI prompt builder</Link>.
        </p>
      </div>
      <aside className="card h-fit">
        <h2 className="h2">Archive</h2>
        <ul className="mt-3 space-y-1 text-sm">
          <li><Link href="/briefing" className="text-accent hover:underline">Live (now)</Link></li>
          {(past ?? []).map((r) => (
            <li key={r.id}>
              <Link href={`/briefing?report=${r.id}`} className="hover:underline">{shortDate(r.created_at)}</Link>
            </li>
          ))}
        </ul>
      </aside>
    </div>
  );
}
